<#
.SYNOPSIS
  Points UAT (Cloud Run) at a Neon Postgres database.

.DESCRIPTION
  Takes the connection string from the Neon console's "Connect" dialog (pooled or direct — both work):

    postgresql://<user>:<password>@ep-xxx[-pooler].<region>.aws.neon.tech/<database>?sslmode=require

  and then:
    1. writes tofu/neon.auto.tfvars (gitignored): pooled + direct host, port, user, database names.
       Tofu builds the JDBC URLs from these (tofu/cloudrun.tf, local.cph_db_env / credit_db_env).
    2. stores the password as a new version of the Secret Manager secrets db-password (cph) and
       credit-db-password (creditService). The password is never written to the repo.
    3. checks that the direct host answers on the Postgres port.

  Then run scripts/bootstrap.ps1 (plan, then -Apply) so Cloud Run picks up the new settings.

.PARAMETER ConnectionString
  Neon connection string. Omit it to be prompted (input hidden).

.PARAMETER CreditDatabase
  Database for creditService, in the same Neon project. Must not be the cph database: both services run
  Flyway and would share one flyway_schema_history table. Create it in Neon first (Databases -> New).

.PARAMETER SkipSecrets
  Only write neon.auto.tfvars; leave Secret Manager alone.

.PARAMETER DestroyOldVersions
  After adding the new password, destroy every older enabled version of the two secrets (irreversible).
  Keeps you within the 6 free secret versions, and removes the old Aiven prod password from GCP.

.EXAMPLE
  pwsh -File scripts/configure-neon-uat.ps1
  pwsh -File scripts/configure-neon-uat.ps1 -ConnectionString 'postgresql://...' -CreditDatabase credit_service
#>
[CmdletBinding()]
param(
  [string]$ConnectionString,
  [string]$CreditDatabase = 'credit_service',
  [string]$Project = 'project-62583e23-5e4b-48e7-b00',
  [switch]$SkipSecrets,
  [switch]$DestroyOldVersions
)
$ErrorActionPreference = 'Stop'

function ConvertFrom-NeonConnectionString([string]$value) {
  $m = [regex]::Match($value.Trim(),
    '^postgres(?:ql)?://(?<user>[^:@/]+):(?<password>[^@]+)@(?<host>[^:/?]+)(?::(?<port>\d+))?/(?<db>[^?]+)')
  if (-not $m.Success) {
    throw "Not a postgresql://user:password@host/database connection string."
  }
  $hostName = $m.Groups['host'].Value
  [pscustomobject]@{
    User       = [uri]::UnescapeDataString($m.Groups['user'].Value)
    Password   = [uri]::UnescapeDataString($m.Groups['password'].Value)
    Port       = if ($m.Groups['port'].Success) { [int]$m.Groups['port'].Value } else { 5432 }
    Database   = [uri]::UnescapeDataString($m.Groups['db'].Value)
    # Neon's pooled endpoint is the compute endpoint id + "-pooler"; strip/add it to get the other one.
    DirectHost = $hostName -replace '^(ep-[^.]+?)-pooler\.', '$1.'
    PooledHost = if ($hostName -match '^ep-[^.]+-pooler\.') { $hostName } else { $hostName -replace '^(ep-[^.]+?)\.', '$1-pooler.' }
  }
}

function Add-SecretVersion([string]$secret, [string]$value) {
  gcloud secrets describe $secret --project=$Project *> $null
  if ($LASTEXITCODE -ne 0) {
    Write-Warning "Secret '$secret' doesn't exist yet (the first tofu apply creates it). Re-run this script with that done."
    return
  }
  $tmp = Join-Path ([IO.Path]::GetTempPath()) ([IO.Path]::GetRandomFileName())
  try {
    [IO.File]::WriteAllText($tmp, $value)   # no trailing newline
    $version = gcloud secrets versions add $secret --project=$Project --data-file=$tmp --format='value(name)'
    if ($LASTEXITCODE -ne 0) { throw "gcloud secrets versions add $secret failed" }
    $newId = ($version -split '/')[-1]
    Write-Host "  $secret -> version $newId"

    if ($DestroyOldVersions) {
      $old = gcloud secrets versions list $secret --project=$Project --filter='state=ENABLED' --format='value(name.basename())' |
        Where-Object { $_ -and $_ -ne $newId }
      foreach ($v in $old) {
        gcloud secrets versions destroy $v --secret=$secret --project=$Project --quiet | Out-Null
        Write-Host "  $secret version $v destroyed"
      }
    }
  } finally {
    Remove-Item $tmp -Force -ErrorAction SilentlyContinue
  }
}

# ─── Input ─────────────────────────────────────────────────────────────────
if (-not $ConnectionString) {
  $secure = Read-Host 'Neon connection string' -AsSecureString
  $ConnectionString = [Runtime.InteropServices.Marshal]::PtrToStringBSTR(
    [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
}
$neon = ConvertFrom-NeonConnectionString $ConnectionString
if ($CreditDatabase -eq $neon.Database) {
  throw "CreditDatabase must differ from the cph database '$($neon.Database)' (each service runs its own Flyway)."
}

# ─── 1. neon.auto.tfvars ───────────────────────────────────────────────────
$tfvars = Join-Path $PSScriptRoot '..\tofu\neon.auto.tfvars'
@"
# Generated by scripts/configure-neon-uat.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Gitignored.
# For CI, paste this file's content into the infra repo secret TOFU_NEON_TFVARS.
uat_db = {
  pooled_host     = "$($neon.PooledHost)"
  direct_host     = "$($neon.DirectHost)"
  port            = $($neon.Port)
  username        = "$($neon.User)"
  cph_database    = "$($neon.Database)"
  credit_database = "$CreditDatabase"
}
"@ | Set-Content -Path $tfvars -Encoding utf8
Write-Host "Wrote $(Resolve-Path $tfvars)"
Write-Host "  cph:           $($neon.User)@$($neon.PooledHost)/$($neon.Database) (Flyway via $($neon.DirectHost))"
Write-Host "  creditService: $($neon.User)@$($neon.DirectHost)/$CreditDatabase"

# ─── 2. Secret Manager ─────────────────────────────────────────────────────
if ($SkipSecrets) {
  Write-Host "Skipped Secret Manager (-SkipSecrets)."
} else {
  Write-Host "Storing the password in Secret Manager ($Project):"
  Add-SecretVersion 'db-password' $neon.Password
  Add-SecretVersion 'credit-db-password' $neon.Password
}

# ─── 3. Reachability ───────────────────────────────────────────────────────
$tcp = Test-NetConnection -ComputerName $neon.DirectHost -Port $neon.Port -WarningAction SilentlyContinue
if ($tcp.TcpTestSucceeded) {
  Write-Host "Neon reachable at $($neon.DirectHost):$($neon.Port)."
} else {
  Write-Warning "Could not reach $($neon.DirectHost):$($neon.Port) from this machine (firewall / VPN?). Cloud Run may still reach it."
}

Write-Host ""
Write-Host "Next: create database '$CreditDatabase' in Neon if it doesn't exist, then: pwsh -File scripts/bootstrap.ps1"
